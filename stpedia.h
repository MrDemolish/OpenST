// pole: 0 nazwa, 1 kategoria, 2 opis
inline int find(const Ent *t, int n, int type, int pole)
{
    for (int i = 0; i < n; ++i)
        if (t[i].type == type)
            return pole == 2 ? t[i].desc : (pole == 1 ? t[i].cat : t[i].name);
    return 0;
}

inline int unitNameStr(int type)
{ int n = 0; const Ent *t = unitTable(n); return find(t, n, type, 0); }
inline int bldNameStr(int tobj)
{ int n = 0; const Ent *t = bldTable(n); return find(t, n, tobj, 0); }
inline int unitDescId(int type)
{ int n = 0; const Ent *t = unitTable(n); return find(t, n, type, 2); }
inline int unitCatId(int type)
{ int n = 0; const Ent *t = unitTable(n); return find(t, n, type, 1); }
